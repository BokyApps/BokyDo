// Builds the Android app's time-zone search data from this package, so the phone offers the
// same zones, cities and abbreviations as the web (PLAN §4b). The output is committed; CI runs
// this again and fails if it differs.
import { build } from 'esbuild';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

/** Bundle the TypeScript sources, so the script needs no build step of its own. */
const work = mkdtempSync(join(tmpdir(), 'bokydo-zones-'));
const bundle = join(work, 'timezones.mjs');
await build({
  stdin: {
    contents: "export * from './src/timezones.ts';\nexport * from './src/timezones-data.ts';\n",
    resolveDir: root,
    sourcefile: 'timezones-entry.ts',
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: bundle,
  logLevel: 'warning',
});
const zones = await import(pathToFileURL(bundle).href);

/** Wrap a long list of pairs a few to a line, so the file stays readable. */
function pairs(entries, render) {
  const lines = [];
  for (let i = 0; i < entries.length; i += 4) {
    lines.push(
      '        ' +
        entries
          .slice(i, i + 4)
          .map(render)
          .join(', ') +
        ',',
    );
  }
  return lines.join('\n');
}

const countries = zones.ZONE_COUNTRIES.map(([id, cc]) => `"${id}" to "${cc}"`);
const aliases = Object.entries(zones.CITY_ALIASES).map(([name, zone]) => `"${name}" to "${zone}"`);
const abbreviations = Object.entries(zones.ABBREVIATIONS).map(
  ([abbr, ids]) => `"${abbr}" to listOf(${ids.map((z) => `"${z}"`).join(', ')})`,
);

rmSync(work, { recursive: true, force: true });

const kotlin = `package com.bokyapps.bokydo.core

// Generated by \`pnpm --filter @bokydo/shared build:android\` from packages/shared. Do not edit.
// AGPL-3.0-only. The web's own time-zone search data (PLAN §4b).

/** The zones, cities and abbreviations the time-zone picker searches. */
object ZoneData {
    /** IANA zone → ISO 3166 country code (from tzdata's zone.tab). */
    val countries: Map<String, String> = mapOf(
${pairs(countries, (l) => l)}
    )

    /** Cities that share another city's zone ("Cape Town" → Africa/Johannesburg). */
    val cityAliases: Map<String, String> = mapOf(
${pairs(aliases, (l) => l)}
    )

    /** Common abbreviations → the zones they are used for. */
    val abbreviations: Map<String, List<String>> = mapOf(
${pairs(abbreviations, (l) => l)}
    )
}
`;

const file = fileURLToPath(
  new URL(
    '../../../apps/android/core/src/main/kotlin/com/bokyapps/bokydo/core/ZoneData.kt',
    import.meta.url,
  ),
);
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, kotlin);
console.log(`Wrote ${file}`);
