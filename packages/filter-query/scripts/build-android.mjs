// Builds the saved-filter engine for the Android app (ADR 0016) into its assets. The output is
// committed; CI runs this again and fails if the committed copy differs, so the phone's filter
// parser can't drift from the web's.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
await build({
  stdin: {
    contents:
      "import { filterJson } from './src/bridge.ts';\nglobalThis.bokydoFilter = filterJson;\n",
    resolveDir: root,
    sourcefile: 'android-entry.ts',
    loader: 'ts',
  },
  // The parser is bundled from source (like the tests do), not from the built package.
  alias: { '@bokydo/nlp': fileURLToPath(new URL('../../nlp/src/index.ts', import.meta.url)) },
  bundle: true,
  format: 'iife',
  minify: true,
  target: 'es2020',
  legalComments: 'none',
  banner: {
    js: '// Generated by `pnpm --filter @bokydo/filter-query build:android` from packages/filter-query. Do not edit. AGPL-3.0-only.',
  },
  outfile: fileURLToPath(
    new URL('../../../apps/android/app/src/main/assets/filter.js', import.meta.url),
  ),
  logLevel: 'warning',
});
