// Builds the Android app's theme data from this package: the Compose colour schemes
// (apps/android/core/.../ThemeTokens.kt) and the bundled font files (res/font/*.ttf).
// The outputs are committed; CI runs this again and fails if they differ, so the phone's
// themes and fonts can never drift from the web's.
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { decompress } from 'wawoff2';

const root = fileURLToPath(new URL('..', import.meta.url));
const require = createRequire(import.meta.url);

/** Bundle the TypeScript sources, so the script needs no build step of its own. */
const work = mkdtempSync(join(tmpdir(), 'bokydo-themes-'));
const bundle = join(work, 'themes.mjs');
await build({
  stdin: {
    contents: "export * from './src/index.ts';",
    resolveDir: root,
    sourcefile: 'themes-entry.ts',
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: bundle,
  logLevel: 'warning',
});
const themes = await import(pathToFileURL(bundle).href);

/** `#rrggbb` → 0xFFrrggbb (opaque ARGB, as Compose wants it). */
const argb = (hex) => {
  const h = hex.replace('#', '');
  return `0xFF${h.toUpperCase()}`;
};

const tokenFields = [
  'bg',
  'surface',
  'surfaceAlt',
  'border',
  'fg',
  'muted',
  'accent',
  'accentFg',
  'danger',
  'warning',
  'success',
  'p1',
  'p2',
  'p3',
  'p4',
];

const projectEntries = (tokens) =>
  Object.entries(tokens.project)
    .map(([name, hex]) => `"${name}" to ${argb(hex)}`)
    .join(', ');

const themeLines = themes.THEMES.map((t) => {
  const colors = tokenFields.map((f) => argb(t.tokens[f])).join(', ');
  return `        ThemeDef("${t.id}", "${t.family}", "${t.name}", "${t.mode}", ThemeTokens(${
    colors
  }, mapOf(${projectEntries(t.tokens)}))),`;
});

const familyLines = themes.FAMILIES.map(
  (f) => `        ThemeFamily("${f.id}", "${f.name}", "${f.defaultLight}", "${f.defaultDark}"),`,
);

const kotlin = `package com.bokyapps.bokydo.core

// Generated by \`pnpm --filter @bokydo/themes build:android\` from packages/themes. Do not edit.
// AGPL-3.0-only. The colours are the web's semantic tokens, so the phone and the browser
// show the same theme.

/** The semantic colours of one theme variant, as opaque ARGB. */
data class ThemeTokens(
${tokenFields.map((f) => `    val ${f}: Long,`).join('\n')}
    /** Project and label colours, tuned per theme so they stay readable. */
    val project: Map<String, Long>,
)

/** One theme variant: an id, the family it belongs to and its mode. */
data class ThemeDef(
    val id: String,
    val family: String,
    val name: String,
    val mode: String,
    val tokens: ThemeTokens,
)

/** A theme family: a light and a dark variant with it. */
data class ThemeFamily(val id: String, val name: String, val defaultLight: String, val defaultDark: String)

object Themes {
    val families: List<ThemeFamily> = listOf(
${familyLines.join('\n')}
    )

    val all: List<ThemeDef> = listOf(
${themeLines.join('\n')}
    )

    private val byId = all.associateBy { it.id }

    fun byId(id: String): ThemeDef? = byId[id]

    fun family(id: String): ThemeFamily? = families.firstOrNull { it.id == id }

    /** The variants of one mode, in family order. */
    fun ofMode(mode: String): List<ThemeDef> = all.filter { it.mode == mode }
}
`;

rmSync(work, { recursive: true, force: true });

const tokensFile = fileURLToPath(
  new URL(
    '../../../apps/android/core/src/main/kotlin/com/bokyapps/bokydo/core/ThemeTokens.kt',
    import.meta.url,
  ),
);
mkdirSync(dirname(tokensFile), { recursive: true });
writeFileSync(tokensFile, kotlin);
console.log(`Wrote ${tokensFile}`);

// ---- fonts ----

/**
 * The font files the web serves, as Android resources. The web's woff2 files are converted to
 * TTF (Android's font resources are not woff2); the variable families keep their weight axis.
 */
const FONT_SOURCES = {
  inter: {
    pkg: '@fontsource-variable/inter',
    file: 'files/inter-latin-wght-normal.woff2',
    variable: true,
  },
  'ibm-plex-sans': {
    pkg: '@fontsource/ibm-plex-sans',
    file: 'files/ibm-plex-sans-latin-400-normal.woff2',
  },
  atkinson: {
    pkg: '@fontsource/atkinson-hyperlegible',
    file: 'files/atkinson-hyperlegible-latin-400-normal.woff2',
  },
  lexend: {
    pkg: '@fontsource-variable/lexend',
    file: 'files/lexend-latin-wght-normal.woff2',
    variable: true,
  },
  opendyslexic: {
    pkg: '@fontsource/opendyslexic',
    file: 'files/opendyslexic-latin-400-normal.woff2',
  },
  'jetbrains-mono': {
    pkg: '@fontsource-variable/jetbrains-mono',
    file: 'files/jetbrains-mono-latin-wght-normal.woff2',
    variable: true,
  },
  'fira-code': {
    pkg: '@fontsource-variable/fira-code',
    file: 'files/fira-code-latin-wght-normal.woff2',
    variable: true,
  },
};

/** The font ids in `src/fonts.ts` that have no file (the system font). */
const systemFonts = themes.FONTS.filter((f) => !FONT_SOURCES[f.id]).map((f) => f.id);

const fontDir = fileURLToPath(
  new URL('../../../apps/android/app/src/main/res/font/', import.meta.url),
);
mkdirSync(fontDir, { recursive: true });

const bundled = [];
for (const [id, source] of Object.entries(FONT_SOURCES)) {
  const pkgDir = dirname(require.resolve(`${source.pkg}/package.json`));
  const woff2 = readFileSync(join(pkgDir, source.file));
  const ttf = await decompress(woff2);
  const name = id.replace(/-/g, '_');
  writeFileSync(join(fontDir, `${name}.ttf`), ttf);
  bundled.push({ id, name, variable: source.variable === true });
  console.log(`Wrote res/font/${name}.ttf (${ttf.length} bytes)`);
}

const fontMeta = `package com.bokyapps.bokydo.core

// Generated by \`pnpm --filter @bokydo/themes build:android\` from packages/themes. Do not edit.
// AGPL-3.0-only.

/** The font families bundled in the app (the system font needs no file). */
object BundledFonts {
    /** Font id → the resource name in res/font. */
    val files: Map<String, String> = mapOf(
${bundled.map((f) => `        "${f.id}" to "${f.name}",`).join('\n')}
    )

    /** The families that keep a weight axis, so a heavier weight is not faked. */
    val variable: Set<String> = setOf(
${bundled
  .filter((f) => f.variable)
  .map((f) => `        "${f.id}",`)
  .join('\n')}
    )

    /** The font choices: id → the name shown in the settings. */
    val names: Map<String, String> = mapOf(
${themes.FONTS.map((f) => `        "${f.id}" to "${f.name}",`).join('\n')}
    )
}
`;
const fontFile = fileURLToPath(
  new URL(
    '../../../apps/android/core/src/main/kotlin/com/bokyapps/bokydo/core/BundledFonts.kt',
    import.meta.url,
  ),
);
writeFileSync(fontFile, fontMeta);
console.log(`Wrote ${fontFile}`);
if (systemFonts.length !== 1 || systemFonts[0] !== 'system')
  throw new Error(`Unexpected font ids without a file: ${systemFonts.join(', ')}`);
