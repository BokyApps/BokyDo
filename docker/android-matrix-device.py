class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise RuntimeError("Fixture API redirects are forbidden")


opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())


def api(path, method="GET", body=None):
    req = urllib.request.Request(fixture["session"]["origin"] + path, headers={"Authorization": "Bearer " + fixture["session"]["accessToken"], "Content-Type": "application/json"}, method=method, data=None if body is None else json.dumps(body).encode())
    with opener.open(req, timeout=15) as response:
        return None if response.status == 204 else json.load(response)


