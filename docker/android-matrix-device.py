"""Run one signed-release matrix row on an already booting disposable emulator.

Provision SDK images/AVDs separately; this runner retains app data and never touches a phone.
The fixture must be generated by android-widgets-fixture.mjs on a throwaway loopback server.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import time
import urllib.request

parser = argparse.ArgumentParser()
parser.add_argument("--api", type=int, required=True, choices=[34, 35, 36])
parser.add_argument("--serial", default="emulator-5562")
parser.add_argument("--apk", type=Path, required=True)
parser.add_argument("--tests", type=Path, required=True)
parser.add_argument("--fixture", type=Path, required=True)
parser.add_argument("--output", type=Path, required=True)
parser.add_argument("--reuse-installed", action="store_true", help="Skip install only when installed APK digests match")
args = parser.parse_args()
assert args.serial.startswith("emulator-"), "Use a disposable emulator"
adb = os.environ.get("ADB", "adb")
args.output.mkdir(parents=True, exist_ok=True, mode=0o700)
args.output.chmod(0o700)
(args.output / "result.json").unlink(missing_ok=True)


def cmd(*parts, timeout=45, check=True):
    result = subprocess.run([adb, "-s", args.serial, *parts], capture_output=True, text=True, timeout=timeout)
    if check and result.returncode:
        raise RuntimeError(result.stdout + result.stderr)
    return result.stdout


def save(name, value):
    (args.output / name).write_text(value)


started = time.time()
print(f"API {args.api}: waiting for boot", flush=True)
deadline = time.monotonic() + 1200
while time.monotonic() < deadline:
    try:
        if cmd("shell", "getprop", "sys.boot_completed", timeout=8, check=False).strip() == "1":
            break
    except subprocess.TimeoutExpired:
        pass
    time.sleep(1)
else:
    raise RuntimeError("Emulator did not boot")
assert cmd("shell", "getprop", "ro.kernel.qemu").strip() == "1"
assert cmd("shell", "getprop", "ro.build.version.sdk").strip() == str(args.api)
fixture = json.loads(args.fixture.read_text())
assert fixture["session"]["origin"] == "http://127.0.0.1:18090"


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise RuntimeError("Fixture API redirects are forbidden")


opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())


def api(path, method="GET", body=None):
    req = urllib.request.Request(fixture["session"]["origin"] + path, headers={"Authorization": "Bearer " + fixture["session"]["accessToken"], "Content-Type": "application/json"}, method=method, data=None if body is None else json.dumps(body).encode())
    with opener.open(req, timeout=15) as response:
        return None if response.status == 204 else json.load(response)


identity = api("/api/v1/sync", "POST", {"cursor": None})
assert identity["user"]["username"] == "widget-fixture", "Refusing a non-fixture account"
project = next(p for p in identity["projects"] if p["id"] == fixture["projectId"])
assert project["name"] == "Widget project" and project["role"] == "owner"

# Only reset the named records belonging to this disposable fixture, never a phone account.
# Remove a previous failed attempt's marker so the final oracle cannot accept old data.
for task in api("/api/v1/tasks")["tasks"]:
    if (task["content"] == f"Matrix task api{args.api}"
            and task["projectId"] == identity["user"]["inboxProjectId"]
            and task["createdById"] == identity["user"]["id"]):
        api("/api/v1/tasks/" + task["id"], "DELETE")
for task in api("/api/v1/tasks?completed=true")["tasks"]:
    if task["content"] == "Project fixture" and task["projectId"] == fixture["projectId"]:
        api("/api/v1/tasks/" + task["id"] + "/uncomplete", "POST", {})
habits = api("/api/v1/habits")
habit = next(h for h in habits["habits"] if h["id"] == fixture["habitId"])
assert habit["name"] == "Daily widget habit"
api("/api/v1/habits/" + habit["id"] + "/check-ins/" + habits["today"], "PUT", {"completed": False})
print(f"API {args.api}: installing exact signed release and private helpers", flush=True)
if args.reuse_installed:
    for package, apk in (("com.bokyapps.bokydo", args.apk), ("com.bokyapps.bokydo.test", args.tests)):
        paths = cmd("shell", "pm", "path", package).strip().splitlines()
        assert len(paths) == 1 and paths[0].startswith("package:/data/app/"), "Expected one installed APK"
        digest = cmd("shell", "sha256sum", paths[0][len("package:"):]).split()[0]
        assert digest == hashlib.sha256(apk.read_bytes()).hexdigest(), "Installed APK does not match candidate"
    save("install.txt", "Reused installed APKs after SHA-256 verification.\n")
else:
    save("install.txt", cmd("install", "--no-incremental", "-r", str(args.apk), timeout=240)
         + cmd("install", "--no-incremental", "-r", "-t", str(args.tests), timeout=240))
cmd("reverse", "tcp:18090", "tcp:18090")
# Guard even WebView subresource redirects: the entire disposable device can only use loopback.
# adb reverse uses the emulator transport and remains available without external IP egress.
assert cmd("shell", "id", "-u").strip() == "0", "Rooted disposable AOSP emulator required"
for firewall in ("iptables", "ip6tables"):
    cmd("shell", firewall, "-w", "-N", "BOKYDO_MATRIX", check=False)
    cmd("shell", firewall, "-w", "-F", "BOKYDO_MATRIX")
    cmd("shell", firewall, "-w", "-A", "BOKYDO_MATRIX", "-o", "lo", "-j", "RETURN")
    cmd("shell", firewall, "-w", "-A", "BOKYDO_MATRIX", "-j", "REJECT")
    cmd("shell", firewall, "-w", "-I", "OUTPUT", "1", "-j", "BOKYDO_MATRIX")
cmd("shell", "appwidget", "grantbind", "--package", "com.bokyapps.bokydo.test", "--user", "0")
print(f"API {args.api}: cold starts", flush=True)
env = dict(os.environ, ADB=adb, BOKYDO_ANDROID_SERIAL=args.serial)
script = Path(__file__).with_name("android-release-startup.py")
startup = subprocess.run([sys.executable, str(script)], env=env, capture_output=True, text=True)
save("cold-starts.txt", startup.stdout + startup.stderr)
if startup.returncode:
    raise RuntimeError("Cold-start failure; see cold-starts.txt")
print(f"API {args.api}: native sign-in, task creation and real widgets", flush=True)
scenario = cmd("shell", "am", "instrument", "-w", "-r", "com.bokyapps.bokydo.test/com.bokyapps.bokydo.ReleaseMatrixInstrumentation", timeout=1800)
save("scenario.txt", scenario)
save("crashes.txt", cmd("logcat", "-b", "crash", "-d"))
assert f"INSTRUMENTATION_RESULT: stream=PASS Android API {args.api}:" in scenario, scenario
print(f"API {args.api}: signed-in process restart", flush=True)
restart = subprocess.run([sys.executable, str(script)], env=dict(env, BOKYDO_ANDROID_EXPECT_TEXT="Today"), capture_output=True, text=True)
save("signed-in-restarts.txt", restart.stdout + restart.stderr)
if restart.returncode:
    raise RuntimeError("Signed-in restart failure")
for _ in range(30):
    opened = api("/api/v1/tasks")["tasks"]
    completed = api("/api/v1/tasks?completed=true")["tasks"]
    habits = api("/api/v1/habits")["habits"]
    checks = {
        "createdTaskPersisted": any(t["content"] == f"Matrix task api{args.api}" for t in opened),
        "widgetTaskCompletionPersisted": any(t["content"] == "Project fixture" for t in completed),
        "widgetHabitCheckInPersisted": any(h["id"] == fixture["habitId"] and h["todayCompleted"] for h in habits),
    }
    if all(checks.values()):
        break
    time.sleep(1)
assert all(checks.values()), checks
cmd("shell", "am", "start", "-n",
    "com.bokyapps.bokydo.test/com.bokyapps.bokydo.testing.MatrixWidgetHostActivity",
    "--ez", "teardown", "true")
result = {
    "api": args.api,
    "android": cmd("shell", "getprop", "ro.build.version.release").strip(),
    "emulatorTimeoutMultiplier": cmd("shell", "getprop", "ro.hw_timeout_multiplier").strip() or "1",
    "fingerprint": cmd("shell", "getprop", "ro.build.fingerprint").strip(),
    "apkSha256": hashlib.sha256(args.apk.read_bytes()).hexdigest(),
    "signedColdStarts": 3,
    "signedInRestarts": 3,
    "nativeOAuth": True,
    "fourTaskWidgetViews": True,
    "habitWidgetAndNavigation": True,
    "backend": checks,
    "elapsedSeconds": round(time.time() - started),
    "browser": "loopback-only WebView fixture browser",
    "widgetHost": "external test APK using framework AppWidgetHost",
}
save("result.pending.json", json.dumps(result, indent=2) + "\n")
(args.output / "result.pending.json").replace(args.output / "result.json")
print(json.dumps(result), flush=True)
